/* 통합과학1 Ⅰ-1 과학의 기본량 — 소단원 잇기 카드
   한 소단원이 뒤 소단원에 넘겨주는 것을 여기 한 곳에 적는다.
   · 넘겨주는 이야기의 결말 아래 '넘겨주기 카드'(sthHandoff)
   · 그것을 쓰는 이야기 맨 앞 '이어받기 카드'(sthBridge) — 앞 소단원을 건너뛰었거나 아직 안 끝냈을 때만 펼쳐진다.
   엔진: ../assets/scope.js. episodes.js·worked.js 다음에 불러온다. */
(function () {
"use strict";

var D01 = [
  "물리량의 기준은 <b>SI 기본량 7개</b>(길이 m · 질량 kg · 시간 s · 전류 A · 온도 K · 물질량 mol · 광도 cd)이고, 넓이·속력·힘 같은 나머지는 모두 이것을 곱하고 나눈 <b>유도량</b>이다.",
  "단위가 다르면 반드시 <b>환산 계수</b>를 곱한다. <b>1 lbf = 4.448222 N</b>. 이 계수를 빠뜨리자 화성 궤도선이 예정보다 훨씬 낮은 57 km까지 내려갔다.",
  "<b>1 m</b>는 빛이 진공에서 <b>1/299,792,458초</b> 동안 간 거리이다. 길이의 기준을 물건이 아니라 빛과 시간으로 정해 두었다."
];
var D02 = [
  "한 걸음에 <b>10배</b>씩. 크기를 <b>10ⁿ m</b>로 적으면 n이 곧 자릿수이다.",
  "두 크기의 배율 = <b>지수의 차</b>. 지구(10⁷ m)는 원자(10⁻¹⁰ m)의 <b>10¹⁷ 배</b>(7 − (−10) = 17).",
  "<b>1 광년</b> = 빛이 1년 동안 가는 거리 = <b>9.46 × 10¹⁵ m</b>."
];

/* 01 → 넘겨주기 */
window.sthHandoff({
  ep: "ep1", title: "이 이야기에서 챙겨 갈 세 줄", lines: D01,
  note: "02 「우주의 스케일」에서는 <b>빛이 가는 시간</b>으로 거리를 재고, 03 「과학적 표기법」에서는 기본량 <b>물질량(mol)</b>으로 분자 수를 셉니다."
});

/* 02 ← 01 */
window.sthBridge({
  ep: "ep2", need: "01", doneKey: "ep1",
  lines: [D01[2], "이 이야기에서는 우주의 먼 거리를 미터 대신 <b>빛이 가는 데 걸리는 시간</b>으로 말합니다. 빛의 속력은 299,792,458 m/s입니다."],
  check: { q: "지금 쓰는 1 m의 정의는?", options: ["파리에 보관한 금속 막대의 길이", "빛이 진공에서 1/299,792,458초 동안 간 거리", "사람 키의 절반쯤"], a: 1, why: "1 m는 빛의 속력과 시간으로 정합니다. 그래서 거리를 빛이 가는 시간으로 바꿔 말할 수 있습니다." }
});

/* 02 → 넘겨주기 */
window.sthHandoff({
  ep: "ep2", title: "이 이야기에서 챙겨 갈 세 줄", lines: D02,
  note: "03 「과학적 표기법」에서 아주 큰 수와 아주 작은 수를 <b>A × 10ⁿ</b>으로 적을 때 이 지수 n이 그대로 쓰입니다."
});

/* 03 ← 02 */
window.sthBridge({
  ep: "ep3", need: "02", doneKey: "ep2",
  lines: [D02[0], D02[1], "이 이야기에서는 그 지수 n을 써서 수를 <b>A × 10ⁿ</b>(1 ≤ A &lt; 10)으로 적습니다. n은 소수점을 옮긴 칸 수입니다."],
  check: { q: "우리은하의 지름(약 10²¹ m)은 사람의 키(약 10⁰ m)의 몇 배일까?", options: ["21배", "10²¹ 배", "10⁻²¹ 배"], a: 1, why: "배율은 지수의 차입니다. 21 − 0 = 21, 곧 10²¹ 배입니다." }
});

/* 03 ← 01 */
window.sthBridge({
  ep: "ep3", need: "01", doneKey: "ep1",
  lines: ["<b>물질량(mol)</b>은 SI 기본량 가운데 하나다. 눈에 보이지 않는 입자를 세는 묶음 단위로, <b>1 mol = 6.02214076 × 10²³ 개</b>(아보가드로수)이다.",
    "이 이야기에서는 <b>물 18.0 g = 1 mol</b>을 써서 물 한 컵에 든 분자 수를 셉니다."],
  check: { q: "다음 가운데 SI 기본량이 아닌 것은?", options: ["물질량 (mol)", "온도 (K)", "넓이 (m²)", "광도 (cd)"], a: 2, why: "넓이는 길이 × 길이로 만든 유도량입니다." }
});
})();
