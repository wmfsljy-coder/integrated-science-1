  check: { q: "열 발이 한곳에 빈틈없이 모였지만 과녁 중심에서 벗어났다. 이 측정은?", options: ["정확하고 정밀하다", "정밀하지만 정확하지 않다", "정확하지만 정밀하지 않다"], a: 1, why: "모인 정도(정밀도)는 좋지만 평균이 참값에서 벗어났습니다. 계통 오차가 있는 경우입니다." }
