/* 통합과학1 Ⅱ-1 자연의 구성 원소 — 소단원 잇기 카드
   한 소단원이 뒤 소단원에 넘겨주는 것을 여기 한 곳에 적는다.
   · 넘겨주는 이야기의 결말 아래 '넘겨주기 카드'(sthHandoff)
   · 그것을 쓰는 이야기 맨 앞 '이어받기 카드'(sthBridge) — 앞 소단원을 건너뛰었거나 아직 안 끝냈을 때만 펼쳐진다.
   엔진: ../assets/scope.js. episodes.js·worked.js 다음에 불러온다. */
(function () {
"use strict";

var D01 = [
  "원소마다 정해진 파장의 선이 있다. 별빛 스펙트럼의 <b>흡수선</b> 자리를 읽으면 그 별을 이루는 원소를 알 수 있다.",
  "빅뱅 뒤 약 <b>3분</b>에 <b>수소 : 헬륨 ≈ 3 : 1</b>(질량비)이 정해졌다. 지금도 우주 질량의 약 74 %가 수소, 약 25 %가 헬륨이다.",
  "질량수 <b>5와 8</b>에 안정한 원자핵이 없어 빅뱅 핵합성은 <b>리튬</b>에서 멈췄다. 탄소 같은 더 무거운 원소는 별이 태어날 때까지 기다려야 했다."
];
var D02 = [
  "별의 중심 온도가 오를수록 수소 → 헬륨 → 탄소·산소 → … → <b>철</b>까지 차례로 핵융합한다. 어디까지 가는지는 <b>별의 질량</b>이 정한다.",
  "핵자당 결합 에너지의 꼭대기는 <b>철-56</b>이다. 철보다 무거운 금·우라늄은 <b>초신성 폭발과 중성자별 충돌</b>에서 만들어진다.",
  "사람 몸무게의 약 <b>90.5 %</b>는 별이 만든 원소이고, 빅뱅에서 온 수소는 9.5 %뿐이다."
];

/* 01 → 넘겨주기 */
window.sthHandoff({
  ep: "ep1", title: "이 이야기에서 챙겨 갈 세 줄", lines: D01,
  note: "02 「별에서 만들어지는 원소」는 빅뱅이 남긴 수소·헬륨에서 출발하고, 03 「원소의 존재비」는 이 <b>우주 조성</b>을 지각·생명체와 견줍니다."
});

/* 02 ← 01 */
window.sthBridge({
  ep: "ep2", need: "01", doneKey: "ep1",
  lines: [D01[1], D01[2], "이 이야기에서는 별 속의 오래가는 높은 온도가 이 벽을 넘어 <b>탄소부터 철까지</b> 만들어 내는 과정을 봅니다."],
  check: { q: "빅뱅 핵합성이 만든 원소로 알맞은 것은?", options: ["탄소와 산소", "수소와 헬륨(그리고 아주 적은 리튬)", "철과 금"], a: 1, why: "질량수 5와 8의 벽 때문에 빅뱅 핵합성은 리튬에서 멈췄습니다. 탄소부터는 별의 몫입니다." }
});

/* 02 → 넘겨주기 */
window.sthHandoff({
  ep: "ep2", title: "이 이야기에서 챙겨 갈 세 줄", lines: D02,
  note: "03 「원소의 존재비」에서 지각과 생명체에 산소·규소·탄소가 많은 까닭을 따질 때 이 <b>원소의 출생지</b>가 바탕이 됩니다."
});

/* 03 ← 01 */
window.sthBridge({
  ep: "ep3", need: "01", doneKey: "ep1",
  lines: [D01[1], "이 이야기에서는 그 우주 조성이 지구에서는 왜 달라졌는지를 <b>탈출 속도</b>로 따집니다."],
  check: { q: "우주 전체에서 질량으로 가장 많은 원소는?", options: ["산소", "수소", "규소", "철"], a: 1, why: "빅뱅이 남긴 수소가 우주 질량의 약 74 %를 차지합니다." }
});
})();
