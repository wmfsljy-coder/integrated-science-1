  "지구시스템은 <b>지권 · 기권 · 수권 · 생물권 · 외권</b>으로 이루어지고, 권역 사이를 <b>물질과 에너지</b>가 끊임없이 오간다.",
  "그래서 한 권역의 사건은 다른 권역에 자취를 남긴다. 예) 화산(지권)이 뿜은 황산 알갱이가 햇빛을 가려 기온(기권)을 낮춘다."
