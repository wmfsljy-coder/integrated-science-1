  "지구시스템을 움직이는 에너지원은 셋이다. <b>태양 복사 에너지</b>(99.9% 넘게) · <b>지구 내부 에너지</b> · <b>조력 에너지</b>.",
  "<b>지구 내부 에너지</b>는 양은 작아도 판 경계처럼 좁은 곳에 몰려 쓰여 <b>맨틀 대류 · 판의 운동 · 화산 · 지진</b>을 일으킨다."
