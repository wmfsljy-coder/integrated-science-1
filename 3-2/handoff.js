/* 통합과학1 Ⅲ-2 역학 시스템 — 소단원 잇기 카드
   한 소단원이 뒤 소단원에 넘겨주는 것을 여기 한 곳에 적는다.
   · 넘겨주는 이야기의 결말 아래 '넘겨주기 카드'(sthHandoff)
   · 그것을 쓰는 이야기 맨 앞 '이어받기 카드'(sthBridge) — 앞 소단원을 건너뛰었거나 아직 안 끝냈을 때만 펼쳐진다.
   엔진: ../assets/scope.js. episodes.js · worked.js 다음에 불러온다. */
(function () {
"use strict";

var D01 = [
  "지구 표면 근처에서 모든 물체는 질량과 상관없이 <b>중력 가속도 g ≈ 9.8 m/s²</b>로 떨어진다. 물체가 받는 중력(무게)은 <b>mg</b>.",
  "<b>자유 낙하</b>하는 물체는 중력만 받아 속도가 <b>1초마다 9.8 m/s씩</b> 빨라진다. v = gt"
];
var D02 = [
  "가속도는 미는 힘 하나가 아니라 <b>알짜힘</b>이 정한다. <b>F = ma</b> (알짜힘이 0이면 속도가 변하지 않는다)",
  "힘은 언제나 두 물체 사이에 <b>짝</b>으로 나타난다(작용 반작용). 0.5초 동안 200 N으로 밀면 두 사람이 받은 <b>충격량</b>은 똑같이 <b>100 N·s</b> = 힘 × 시간."
];

/* 01 → 넘겨주기 */
window.sthHandoff({
  ep: "ep1", title: "이 이야기에서 챙겨 갈 두 줄", lines: D01,
  note: "02 「뉴턴 운동 법칙」에서는 엘리베이터 저울로 <b>mg</b>와 떠받치는 힘을 견주고, 줄이 끊겨 <b>a = −9.8 m/s²</b>(자유 낙하)가 되면 눈금이 어떻게 되는지 봅니다."
});

/* 02 ← 01 */
window.sthBridge({
  ep: "ep2", need: "01", doneKey: "ep1",
  lines: [D01[0], "이 이야기에서는 체중계가 재는 것이 질량이 아니라 <b>떠받치는 힘</b>이라는 것을 확인합니다. 엘리베이터가 자유 낙하하면 그 힘이 0이 됩니다."],
  check: { q: "질량 50 kg인 사람이 받는 중력의 크기는? (g = 9.8 m/s²)", options: ["50 N", "490 N", "5.1 N", "9.8 N"], a: 1, why: "무게 = mg = 50 × 9.8 = 490 N." }
});

/* 02 → 넘겨주기 */
window.sthHandoff({
  ep: "ep2", title: "이 이야기에서 챙겨 갈 두 줄", lines: D02,
  note: "03 「충돌과 운동량 보존」에서는 같은 <b>충격량 = 힘 × 시간</b>을 써서 야구공을 받는 손과 자동차의 크럼플 존을 설계하고, 작용 반작용으로 <b>운동량이 보존</b>되는 까닭을 봅니다."
});

/* 03 ← 02 */
window.sthBridge({
  ep: "ep3", need: "02", doneKey: "ep2",
  lines: [D02[0], D02[1], "이 이야기에서는 충돌하는 두 수레가 서로에게 같은 크기의 충격량을 주고받아 <b>운동량의 합이 그대로</b>인 것을 확인합니다."],
  check: { q: "질량 2 kg인 물체에 알짜힘 6 N이 작용하면 가속도는?", options: ["12 m/s²", "3 m/s²", "0.33 m/s²", "8 m/s²"], a: 1, why: "a = F ÷ m = 6 ÷ 2 = 3 m/s²." }
});
})();
