  "<b>우연 오차</b>는 여러 번 재어 평균 내면 줄지만, 영점이 틀어진 것 같은 <b>계통 오차</b>는 아무리 반복해도 줄지 않아 기기를 <b>교정</b>해야 한다.",
  "적을 수 있는 자리는 자가 정한다. 최소 눈금의 <b>1/10까지 어림</b>한 자리까지가 유효숫자이다."
