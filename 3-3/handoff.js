/* 통합과학1 Ⅲ-3 생명 시스템 — 소단원 잇기 카드
   한 소단원이 뒤 소단원에 넘겨주는 것을 여기 한 곳에 적는다.
   · 넘겨주는 이야기의 결말 아래 '넘겨주기 카드'(sthHandoff)
   · 그것을 쓰는 이야기 맨 앞 '이어받기 카드'(sthBridge) — 앞 소단원을 건너뛰었거나 아직 안 끝냈을 때만 펼쳐진다.
   엔진: ../assets/scope.js. episodes.js · worked.js 다음에 불러온다. */
(function () {
"use strict";

var D01 = [
  "<b>효소</b>는 생명체의 화학 반응이 체온에서도 빠르게 일어나도록 <b>활성화 에너지를 낮춰</b> 주는 생체 촉매다. 반응물·생성물은 바꾸지 않는다.",
  "효소는 <b>단백질</b>이라 짝이 맞는 기질에만 작용하고(기질 특이성), 높은 온도에서는 모양이 풀려 <b>변성</b>된다."
];
var D02 = [
  "몸속 화학 반응을 통틀어 <b>물질대사</b>라 한다. 작은 분자를 큰 분자로 합성하며 에너지를 <b>흡수</b>하면 <b>동화 작용</b>, 큰 분자를 분해하며 에너지를 <b>방출</b>하면 <b>이화 작용</b>.",
  "<b>단백질</b>은 아미노산이 <b>펩타이드 결합</b>으로 줄줄이 이어진 사슬이다. 아미노산 n개를 이으면 결합 n − 1개 — 이것이 동화 작용이다."
];

/* 01 → 넘겨주기 */
window.sthHandoff({
  ep: "ep1", title: "이 이야기에서 챙겨 갈 두 줄", lines: D01,
  note: "02 「동화 작용과 이화 작용」의 세포 호흡과 단백질 합성도 단계마다 <b>효소</b>가 진행시키고, 03 「유전정보의 흐름」에서는 그 효소 같은 <b>단백질</b>을 유전자가 어떻게 지정하는지 봅니다."
});

/* 02 ← 01 */
window.sthBridge({
  ep: "ep2", need: "01", doneKey: "ep1",
  lines: [D01[0], "이 이야기의 세포 호흡과 단백질 조립은 모두 <b>효소가 진행시키는 물질대사</b>입니다. 그래서 체온 37 °C에서도 쉬지 않고 일어납니다."],
  check: { q: "효소가 반응을 빠르게 하는 방법은?", options: ["반응물의 에너지를 높인다", "활성화 에너지를 낮춘다", "생성물의 종류를 바꾼다"], a: 1, why: "효소는 넘어야 할 언덕(활성화 에너지)만 낮춘다. 반응물과 생성물은 그대로다." }
});

/* 02 → 넘겨주기 */
window.sthHandoff({
  ep: "ep2", title: "이 이야기에서 챙겨 갈 두 줄", lines: D02,
  note: "03 「유전정보의 흐름」에서는 리보솜이 mRNA를 읽어 아미노산을 <b>하나씩 이어 붙이는</b> 단백질 합성을, 그 순서를 정하는 DNA와 함께 봅니다."
});

/* 03 ← 02 */
window.sthBridge({
  ep: "ep3", need: "02", doneKey: "ep2",
  lines: [D02[1], D01[1], "이 이야기에서는 DNA의 염기 서열이 그 사슬의 <b>아미노산 순서</b>를 정하고, 한 글자만 바뀌어도 단백질이 달라지는 것을 봅니다."],
  check: { q: "아미노산 10개를 이어 단백질 사슬을 만들면 펩타이드 결합은 몇 개일까?", options: ["10개", "9개", "11개", "20개"], a: 1, why: "사슬의 이음매는 늘 하나 적다. n − 1 = 9개이고, 빠져나오는 물도 9분자다." }
});
})();
